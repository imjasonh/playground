/// Parsed RFC 1952 gzip container view borrowing the raw DEFLATE stream.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GzipFrame<'a> {
    pub deflate_payload: &'a [u8],
    pub expected_crc32: u32,
    pub expected_isize: u32,
}

/// Parse an RFC 1952 gzip container and return its raw DEFLATE slice + trailer fields.
pub fn parse_gzip_frame(gz: &[u8]) -> Result<GzipFrame<'_>, &'static str> {
    if gz.len() < 18 {
        return Err("gzip frame shorter than 18-byte minimum");
    }
    if gz[0] != 0x1F || gz[1] != 0x8B {
        return Err("invalid gzip magic");
    }
    if gz[2] != 0x08 {
        return Err("unsupported gzip compression method");
    }
    let flg = gz[3];
    let mut pos = 10usize;
    let trailer_start = gz.len() - 8;

    // FEXTRA
    if (flg & 0x04) != 0 {
        if pos + 2 > trailer_start {
            return Err("truncated gzip FEXTRA length");
        }
        let xlen = usize::from(u16::from_le_bytes([gz[pos], gz[pos + 1]]));
        pos += 2;
        if pos + xlen > trailer_start {
            return Err("truncated gzip FEXTRA payload");
        }
        pos += xlen;
    }
    // FNAME (NUL-terminated)
    if (flg & 0x08) != 0 {
        while pos < trailer_start && gz[pos] != 0 {
            pos += 1;
        }
        if pos >= trailer_start {
            return Err("unterminated gzip FNAME");
        }
        pos += 1;
    }
    // FCOMMENT (NUL-terminated)
    if (flg & 0x10) != 0 {
        while pos < trailer_start && gz[pos] != 0 {
            pos += 1;
        }
        if pos >= trailer_start {
            return Err("unterminated gzip FCOMMENT");
        }
        pos += 1;
    }
    // FHCRC
    if (flg & 0x02) != 0 {
        if pos + 2 > trailer_start {
            return Err("truncated gzip FHCRC");
        }
        pos += 2;
    }

    let expected_crc32 = u32::from_le_bytes([
        gz[trailer_start],
        gz[trailer_start + 1],
        gz[trailer_start + 2],
        gz[trailer_start + 3],
    ]);
    let expected_isize = u32::from_le_bytes([
        gz[trailer_start + 4],
        gz[trailer_start + 5],
        gz[trailer_start + 6],
        gz[trailer_start + 7],
    ]);

    Ok(GzipFrame {
        deflate_payload: &gz[pos..trailer_start],
        expected_crc32,
        expected_isize,
    })
}

/// Wrap raw DEFLATE bytes and original uncompressed data into an RFC 1952 gzip frame.
pub fn encode_gzip_frame(raw: &[u8], deflate_payload: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(10 + deflate_payload.len() + 8);
    out.extend_from_slice(&[0x1F, 0x8B, 0x08, 0, 0, 0, 0, 0, 0, 0xFF]);
    out.extend_from_slice(deflate_payload);
    out.extend_from_slice(&crc32(raw).to_le_bytes());
    out.extend_from_slice(&(raw.len() as u32).to_le_bytes());
    out
}

/// Compute integer throughput in bytes/second from `bytes` processed in `elapsed_us`.
pub fn throughput_bps(bytes: usize, elapsed_us: u32) -> i64 {
    if elapsed_us == 0 {
        return 0;
    }
    ((bytes as u64).saturating_mul(1_000_000) / u64::from(elapsed_us)) as i64
}

/// Compute compression ratio in milli-x (e.g., 6.79x -> 6790).
pub fn ratio_milli(raw_len: usize, gz_len: usize) -> i64 {
    if gz_len == 0 {
        return 0;
    }
    ((raw_len as u64).saturating_mul(1_000) / (gz_len as u64)) as i64
}

/// Inflate a raw DEFLATE stream into a non-wrapping output buffer using a reusable
/// heap-allocated `miniz_oxide::inflate::core::DecompressorOxide`.
pub fn inflate_miniz_oxide(
    decompressor: &mut miniz_oxide::inflate::core::DecompressorOxide,
    deflate: &[u8],
    out: &mut [u8],
) -> Result<usize, String> {
    use miniz_oxide::inflate::core::decompress;
    use miniz_oxide::inflate::core::inflate_flags::TINFL_FLAG_USING_NON_WRAPPING_OUTPUT_BUF;
    use miniz_oxide::inflate::TINFLStatus;

    decompressor.init();
    let (status, _consumed, written) = decompress(
        decompressor,
        deflate,
        out,
        0,
        TINFL_FLAG_USING_NON_WRAPPING_OUTPUT_BUF,
    );
    match status {
        TINFLStatus::Done => Ok(written),
        other => Err(format!("miniz_oxide inflate failed: {other:?}")),
    }
}

