"""Pixel art for Rampart: body-plate portraits, board mechs, and
damage overlays.

Pictures are rows of palette indices written as characters:

    .  universal black (0 also works, for black inside a part)
    1  dark gray: the steel frame, joints, and shadow
    2  the player's mid color: painted armor
    3  the player's light color: highlights, lenses, blades

Light comes from the top left. Each portrait is drawn band by band,
one band per row of body-plate cells, so every part stays inside the
cells a shot must land in to hit it.
"""


INDEX = {".": 0, "0": 0, "1": 1, "2": 2, "3": 3}


def picture(rows):
    """Parse 48 rows of six '|'-separated 8-pixel cells."""
    assert len(rows) == 48, len(rows)
    out = []
    for y, row in enumerate(rows):
        cells = row.split("|")
        assert len(cells) == 6 and all(len(c) == 8 for c in cells), (y, row)
        out.append([INDEX[ch] for ch in "".join(cells)])
    return out


