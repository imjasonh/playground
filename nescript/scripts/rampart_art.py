def split16(rows):
    """Split a 16x16 picture into TL, TR, BL, BR 8x8 tiles."""
    return [
        [r[:8] for r in rows[:8]],
        [r[8:] for r in rows[:8]],
        [r[:8] for r in rows[8:]],
        [r[8:] for r in rows[8:]],
    ]


