def charred(pixels):
    """The same picture one shade darker, for wrecked locations."""
    return [[(0, 0, 1, 2)[v] for v in row] for row in pixels]


def tiles_of(pixels, cols, rows):
    """Cut a picture into 8x8 tiles in reading order, as '.123' rows."""
    out = []
    for r in range(rows):
        for col in range(cols):
            tile = []
            for y in range(8):
                line = pixels[r * 8 + y][col * 8 : col * 8 + 8]
                tile.append("".join(".123"[v] for v in line))
            out.append(tile)
    return out
