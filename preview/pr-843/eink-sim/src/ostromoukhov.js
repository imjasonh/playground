// Pre-normalized weights: flat Float32Array of length 256 * 3.
export const OSTROMOUKHOV_WEIGHTS = new Float32Array(256 * 3);
for (let i = 0; i < 256; i++) {
  const [d1, d2, d3] = RAW_128[i > 127 ? 255 - i : i];
  const sum = d1 + d2 + d3;
  OSTROMOUKHOV_WEIGHTS[i * 3] = d1 / sum;
  OSTROMOUKHOV_WEIGHTS[i * 3 + 1] = d2 / sum;
  OSTROMOUKHOV_WEIGHTS[i * 3 + 2] = d3 / sum;
}
