// Command gen writes the protobuf schema of the built-in Kubernetes types
// that package protobuf decodes, from the protobuf struct tags on the Go
// types in k8s.io/api. It's a separate module so that the kube module never
// depends on k8s.io/api. Run it from this directory after changing the
// k8s.io/api version in go.mod:
//
//	go run . -o ../schema.txt
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"maps"
	"os"
	"reflect"
	"regexp"
	"runtime/debug"
	"slices"
	"strconv"
	"strings"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/client-go/kubernetes/scheme"
)

type field struct {
	json string // "-" for a field whose message's fields are inline in JSON
	num  int
	typ  string
}

type message struct {
	name    string
	wrapper bool // a named slice: a message with repeated field 1, an array in JSON
	fields  []field
}

type gen struct {
	msgs  map[string]*message
	kinds map[string]string // "apiVersion kind" -> message
}

func main() {
	out := flag.String("o", "../schema.txt", "output file")
	flag.Parse()
	g := &gen{msgs: map[string]*message{}, kinds: map[string]string{}}
	// Alpha and beta versions are left out to keep the schema small; types
	// that aren't in it are read as JSON.
	stable := regexp.MustCompile(`^v[0-9]+$`)
	for gvk, t := range scheme.Scheme.AllKnownTypes() {
		if !stable.MatchString(gvk.Version) || !isProto(t) {
			continue
		}
		name := g.message(t)
		if !g.hasMetadata(name) {
			continue
		}
		g.kinds[gvk.GroupVersion().String()+" "+gvk.Kind] = name
	}
	for kind, v := range map[string]any{
		"PartialObjectMetadata":     metav1.PartialObjectMetadata{},
		"PartialObjectMetadataList": metav1.PartialObjectMetadataList{},
		"Status":                    metav1.Status{},
	} {
		g.kinds["meta.k8s.io/v1 "+kind] = g.message(reflect.TypeOf(v))
	}

	f, err := os.Create(*out)
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(f)
	version := "unknown"
	if bi, ok := debug.ReadBuildInfo(); ok {
		for _, d := range bi.Deps {
			if d.Path == "k8s.io/api" {
				version = d.Version
			}
		}
	}
	fmt.Fprintf(w, "# The protobuf schema of built-in Kubernetes types, from k8s.io/api %s.\n", version)
	fmt.Fprintln(w, "# Generated by internal/protobuf/gen. DO NOT EDIT.")
	for _, k := range slices.Sorted(maps.Keys(g.kinds)) {
		fmt.Fprintf(w, "kind %s %s\n", k, g.kinds[k])
	}
	// Kinds that were left out still added their messages; write only the
	// messages that the kinds in the schema use.
	used := map[string]bool{}
	var use func(name string)
	use = func(name string) {
		if used[name] {
			return
		}
		used[name] = true
		for _, f := range g.msgs[name].fields {
			if _, ref, ok := strings.Cut(f.typ, "msg:"); ok {
				use(ref)
			}
		}
	}
	for _, name := range g.kinds {
		use(name)
	}
	for _, name := range slices.Sorted(maps.Keys(used)) {
		m := g.msgs[name]
		if m.wrapper {
			fmt.Fprintf(w, "message %s wrapper\n", name)
		} else {
			fmt.Fprintf(w, "message %s\n", name)
		}
		for _, fl := range m.fields {
			fmt.Fprintf(w, "\t%s %d %s\n", fl.json, fl.num, fl.typ)
		}
	}
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
}

// isProto reports whether t has generated protobuf code.
func isProto(t reflect.Type) bool {
	pt := reflect.PointerTo(t)
	_, m := pt.MethodByName("Marshal")
	_, u := pt.MethodByName("Unmarshal")
	return m && u
}

func (g *gen) hasMetadata(name string) bool {
	for _, f := range g.msgs[name].fields {
		if f.json == "metadata" && f.num == 1 {
			return true
		}
	}
	return false
}

// messageName names a Go type's message after its package, shortened.
func messageName(t reflect.Type) string {
	p := t.PkgPath()
	switch {
	case strings.HasPrefix(p, "k8s.io/api/"):
		p = strings.TrimPrefix(p, "k8s.io/api/")
	case strings.HasPrefix(p, "k8s.io/apimachinery/pkg/apis/"):
		p = strings.TrimPrefix(p, "k8s.io/apimachinery/pkg/apis/")
	case strings.HasPrefix(p, "k8s.io/apimachinery/pkg/api/"):
		p = strings.TrimPrefix(p, "k8s.io/apimachinery/pkg/api/")
	case strings.HasPrefix(p, "k8s.io/apimachinery/pkg/util/"):
		p = strings.TrimPrefix(p, "k8s.io/apimachinery/pkg/util/")
	case strings.HasPrefix(p, "k8s.io/apimachinery/pkg/"):
		p = strings.TrimPrefix(p, "k8s.io/apimachinery/pkg/")
	}
	return strings.ReplaceAll(p, "/", ".") + "." + t.Name()
}

// special messages have a JSON form that isn't an object. The decoder knows
// them by name; their fields are written like any other message's.
var special = map[string]bool{
	"meta.v1.Time": true, "meta.v1.MicroTime": true, "meta.v1.Duration": true,
	"resource.Quantity": true, "intstr.IntOrString": true,
	"runtime.RawExtension": true, "meta.v1.FieldsV1": true,
}

// message returns the name of t's message, adding it and the messages it
// refers to.
func (g *gen) message(t reflect.Type) string {
	name := messageName(t)
	if _, ok := g.msgs[name]; ok {
		return name
	}
	m := &message{name: name}
	g.msgs[name] = m
	switch name {
	case "meta.v1.Time", "meta.v1.MicroTime":
		m.fields = []field{{"seconds", 1, "int64"}, {"nanos", 2, "int32"}}
		return name
	case "meta.v1.Duration":
		m.fields = []field{{"duration", 1, "int64"}}
		return name
	case "resource.Quantity":
		m.fields = []field{{"string", 1, "string"}}
		return name
	case "intstr.IntOrString":
		m.fields = []field{{"type", 1, "int64"}, {"intVal", 2, "int32"}, {"strVal", 3, "string"}}
		return name
	case "runtime.RawExtension", "meta.v1.FieldsV1":
		m.fields = []field{{"raw", 1, "bytes"}}
		return name
	}
	if t.Kind() == reflect.Slice {
		m.wrapper = true
		m.fields = []field{{"items", 1, "[]" + g.typeOf(t.Elem())}}
		return name
	}
	g.fields(t, m)
	slices.SortFunc(m.fields, func(a, b field) int { return a.num - b.num })
	return name
}

func (g *gen) fields(t reflect.Type, m *message) {
	for i := range t.NumField() {
		f := t.Field(i)
		tag := f.Tag.Get("protobuf")
		if tag == "" {
			continue
		}
		parts := strings.Split(tag, ",")
		num, err := strconv.Atoi(parts[1])
		if err != nil {
			log.Fatalf("%v.%s: bad protobuf tag %q", t, f.Name, tag)
		}
		json, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
		switch {
		case json == "-":
			continue
		case json == "" && (f.Anonymous || strings.Contains(opts, "inline")):
			// encoding/json puts the fields of an embedded struct with no
			// name in the parent's object; protobuf nests them.
			json = "-"
		case json == "":
			continue
		}
		var typ string
		if f.Type.Kind() == reflect.Map {
			typ = "map:" + g.typeOf(f.Type.Key()) + ":" + g.typeOf(f.Type.Elem())
		} else {
			typ = g.typeOf(f.Type)
		}
		m.fields = append(m.fields, field{json: json, num: num, typ: typ})
	}
}

// typeOf returns the schema type of a Go type: a scalar name, msg:NAME, or
// []TYPE for a repeated field.
func (g *gen) typeOf(t reflect.Type) string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Name() != "" && special[messageName(t)] {
		return "msg:" + g.message(t)
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "bool"
	case reflect.Int32:
		return "int32"
	case reflect.Int64:
		return "int64"
	case reflect.Uint32:
		return "uint32"
	case reflect.Uint64:
		return "uint64"
	case reflect.Float64:
		return "double"
	case reflect.Float32:
		return "float"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "bytes"
		}
		if t.Name() != "" && isProto(t) {
			return "msg:" + g.message(t)
		}
		return "[]" + g.typeOf(t.Elem())
	case reflect.Struct:
		return "msg:" + g.message(t)
	}
	log.Fatalf("unsupported type %v", t)
	return ""
}
