#!/usr/bin/env python3
"""Writes C3BootProofs/Proofs/LoadedImage.lean: `Loaded M`, which says that
memory `M` holds every piece of the bootloader image that
`scripts/extract-functions.py` extracted, at its link address, and a lemma
`Loaded.<name>` for each piece that gives its `CodeIn`.

The pieces are the `<name>Address` definitions in C3BootProofs/Image/ that
have a `<name>Code` or `<name>Data` list beside them. `extract-functions.py`
reads each one out of a segment of the image that the ROM loader copies to
RAM, so every byte of a piece is a byte that the loader writes. `Loaded`
lists the pieces in address order. A piece that lies inside another one,
such as `p256Modulus` inside `p256Params`, isn't listed: its lemma reads it
out of the larger piece with `CodeIn.sub`.

Run it from c3-boot-proofs/ after the image files change.
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
IMAGE = os.path.join(ROOT, 'C3BootProofs', 'Image')
OUT = os.path.join(ROOT, 'C3BootProofs', 'Proofs', 'LoadedImage.lean')

# The image's data-bus and instruction-bus ranges that `Loaded` covers: the
# read-only data below 0x3FCC8000, where the bootloader's stack ends, and
# IRAM, which bootloader.x places at 0x403A0000 with length 0x24000.
DRAM = (0x3FCC4000, 0x3FCC8000)
IRAM = (0x403A0000, 0x403C4000)

DEF = re.compile(r'^def (\w+) : (Nat|List Nat) :=\s*(\[[^\]]*\]|0x[0-9a-fA-F]+|\d+)', re.M)


def image_files():
    names = []
    for path in sorted(glob.glob(os.path.join(IMAGE, '*.lean'))):
        base = os.path.basename(path)[:-len('.lean')]
        if base in ('Addr', 'BootloaderV0'):
            continue
        names.append(base)
    return names


def pieces():
    defs = {}
    for base in image_files():
        with open(os.path.join(IMAGE, base + '.lean')) as f:
            text = f.read()
        for m in DEF.finditer(text):
            assert m.group(1) not in defs, m.group(1)
            defs[m.group(1)] = (m.group(2), m.group(3))
    out = []
    for name, (kind, value) in defs.items():
        if not name.endswith('Address') or kind != 'Nat':
            continue
        stem = name[:-len('Address')]
        found = [s for s in ('Code', 'Data') if stem + s in defs]
        assert len(found) <= 1, stem
        if not found:
            continue
        body = [int(t, 0) for t in re.findall(r'0x[0-9a-fA-F]+|\d+', defs[stem + found[0]][1])]
        assert all(0 <= b < 256 for b in body), stem
        out.append((stem, found[0], int(value, 0), body))
    return out


def plan():
    """The listed pieces in address order, and each contained piece with the
    listed piece that holds it."""
    ps = sorted(pieces(), key=lambda p: (p[2], -len(p[3]), p[0]))
    listed, inside = [], []
    for p in ps:
        if listed and p[2] < listed[-1][2] + len(listed[-1][3]):
            q = listed[-1]
            off = p[2] - q[2]
            assert off + len(p[3]) <= len(q[3]), (p[0], q[0])
            assert q[3][off:off + len(p[3])] == p[3], (p[0], q[0])
            inside.append((p, q, off))
        else:
            listed.append(p)
    for p in listed:
        lo, hi = DRAM if p[2] < 0x40000000 else IRAM
        assert lo <= p[2] and p[2] + len(p[3]) <= hi, p[0]
    return listed, inside


def lean_name(p):
    return p[0] + p[1]


HEADER = '''import C3BootProofs.Proofs.Loaded
{imports}

/-!
# The memory that the ROM loader leaves

Generated by `scripts/gen-loaded.py` from the image files. Do not edit.

`Loaded M` says that memory `M` holds the {n} pieces of the bootloader image
that `scripts/extract-functions.py` extracted, each at its link address:
{code} function bodies in IRAM, at 0x403A0000 to 0x{code_end:X}, and {data}
pieces of read-only data at 0x3FCC4000 to 0x{data_end:X}. The function
bodies cover the image's `.text` without a gap. `extract-functions.py`
reads every piece out of a segment of the image that the ROM loader copies
to RAM, and fails when a piece isn't inside one, so `Loaded` is what the
loader leaves at those addresses. It says nothing about the other bytes of
the loaded segments, which no proof reads.

`Loaded.<name>` gives the `CodeIn` of the piece `<name>`. The {inside}
pieces that lie inside another one aren't listed in `imagePieces`; their
lemmas read them out of the larger piece. `loaded_imageMem` shows that
`Loaded` holds of a memory, so it isn't a vacuous hypothesis.
-/

namespace C3.RV32

open C3.Image

/-- The image's pieces that don't lie inside another piece, in address
order. -/
def imagePieces : List (Nat × List Nat) :=
  [{pieces}]

set_option maxRecDepth 10000 in
theorem imagePieces_length : imagePieces.length = {n_listed} := rfl

/-- The listed pieces are in address order and don't overlap. -/
theorem imagePieces_ok : piecesOk imagePieces = true := by decide +kernel

/-- Every listed piece lies in the image's read-only data, at 0x{dlo:X} to
0x{dhi:X}, or in IRAM, at 0x{ilo:X} to 0x{ihi:X}. -/
theorem imagePieces_within : piecesWithin 0x{dlo:X} 0x{dhi:X} 0x{ilo:X} 0x{ihi:X} imagePieces = true := by
  decide +kernel

/-- Memory `M` holds every piece of the bootloader image that the proofs
read, each at its link address, as the ROM loader leaves it. -/
def Loaded (M : Word → BitVec 8) : Prop := PiecesIn M imagePieces

/-- The image's pieces at their addresses, and 0 elsewhere. -/
def imageMem : Word → BitVec 8 := piecesMem imagePieces

theorem loaded_imageMem : Loaded imageMem := piecesIn_mem imagePieces_ok

/-- `Loaded` carries over to memory that agrees on the image's read-only
data and IRAM. -/
theorem Loaded.congr {{M M' : Word → BitVec 8}} (h : Loaded M)
    (hx : ∀ x : Word, (0x{dlo:X} ≤ x.toNat ∧ x.toNat < 0x{dhi:X}) ∨ (0x{ilo:X} ≤ x.toNat ∧ x.toNat < 0x{ihi:X}) →
      M' x = M x) : Loaded M' :=
  PiecesIn.congr h imagePieces_within (by decide) (by decide) hx

theorem loaded_get {{M : Word → BitVec 8}} (h : Loaded M) (k : Nat) {{a : Nat}} {{c : List Nat}}
    (hk : k < {n_listed}) (he : imagePieces[k]'(Nat.lt_of_lt_of_eq hk imagePieces_length.symm) = (a, c)) :
    CodeIn M (BitVec.ofNat 32 a) c := by
  have := h k (Nat.lt_of_lt_of_eq hk imagePieces_length.symm)
  rw [he] at this
  exact this
'''

LISTED = '''
theorem Loaded.{stem} {{M : Word → BitVec 8}} (h : Loaded M) :
    CodeIn M (BitVec.ofNat 32 {stem}Address) {name} :=
  loaded_get h {k} (by decide) rfl
'''

INSIDE = '''
/-- `{stem}` lies {where}. -/
theorem Loaded.{stem} {{M : Word → BitVec 8}} (h : Loaded M) :
    CodeIn M (BitVec.ofNat 32 {stem}Address) {name} :=
  CodeIn.sub h.{outer} {off} (by decide +kernel) (by decide +kernel)
'''


def main():
    listed, inside = plan()
    code = [p for p in listed if p[2] >= 0x40000000]
    data = [p for p in pieces() if p[2] < 0x40000000]
    text = HEADER.format(
        imports='\n'.join('import C3BootProofs.Image.' + b for b in image_files()),
        n=len(listed) + len(inside), code=len(code), data=len(data),
        code_end=max(p[2] + len(p[3]) for p in code),
        data_end=max(p[2] + len(p[3]) for p in data),
        inside=len(inside), n_listed=len(listed),
        pieces=',\n    '.join('(%sAddress, %s)' % (p[0], lean_name(p)) for p in listed),
        dlo=DRAM[0], dhi=DRAM[1], ilo=IRAM[0], ihi=IRAM[1])
    for k, p in enumerate(listed):
        text += LISTED.format(stem=p[0], name=lean_name(p), k=k)
    for p, q, off in inside:
        where = ('at the start of `%s`' % q[0]) if off == 0 else ('%d bytes into `%s`' % (off, q[0]))
        text += INSIDE.format(stem=p[0], name=lean_name(p), outer=q[0], off=off, where=where)
    text += '\nend C3.RV32\n'
    with open(OUT, 'w') as f:
        f.write(text)


if __name__ == '__main__':
    main()
